    DEPT_CD      VARCHAR(10)  NOT NULL,
    PROC_STS     VARCHAR(10)  NOT NULL DEFAULT 'DONE',
    RMRK_TXT     VARCHAR(300),
    CONSTRAINT PK_TB_PROC_HIST PRIMARY KEY (PROC_ID),
    CONSTRAINT FK_PROC_ENC FOREIGN KEY (ENC_ID) REFERENCES TB_ENC_HIST (ENC_ID),
    CONSTRAINT FK_PROC_PT FOREIGN KEY (PT_NO) REFERENCES TB_PT_MST (PT_NO),
    CONSTRAINT FK_PROC_CD FOREIGN KEY (PROC_CD) REFERENCES TB_PROC_MST (PROC_CD),
    CONSTRAINT FK_PROC_PROV FOREIGN KEY (PROV_ID) REFERENCES TB_PROVIDER (PROV_ID),
    CONSTRAINT FK_PROC_DEPT FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT_MST (DEPT_CD)
);

