-- ------------------------------------------------------------
-- Master / Code tables
-- ------------------------------------------------------------

CREATE TABLE TB_CODE_MST (
    CD_GRP       VARCHAR(20)  NOT NULL,
    CD_VAL       VARCHAR(20)  NOT NULL,
    CD_NM        VARCHAR(100) NOT NULL,
    CD_DESC      VARCHAR(300),
    SORT_ORD     INTEGER      NOT NULL DEFAULT 0,
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    REG_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TB_CODE_MST PRIMARY KEY (CD_GRP, CD_VAL)
);

CREATE TABLE TB_DEPT_MST (
    DEPT_CD      VARCHAR(10)  NOT NULL,
    DEPT_NM      VARCHAR(100) NOT NULL,
    DEPT_TYP     VARCHAR(20)  NOT NULL,
    UP_DEPT_CD   VARCHAR(10),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    REG_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TB_DEPT_MST PRIMARY KEY (DEPT_CD),
    CONSTRAINT FK_DEPT_UP FOREIGN KEY (UP_DEPT_CD) REFERENCES TB_DEPT_MST (DEPT_CD)
);

CREATE TABLE TB_WARD_MST (
    WARD_CD      VARCHAR(10)  NOT NULL,
    WARD_NM      VARCHAR(100) NOT NULL,
    BED_CNT      INTEGER      NOT NULL DEFAULT 0,
    DEPT_CD      VARCHAR(10),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_WARD_MST PRIMARY KEY (WARD_CD),
    CONSTRAINT FK_WARD_DEPT FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT_MST (DEPT_CD)
);

CREATE TABLE TB_PROVIDER (
    PROV_ID      VARCHAR(20)  NOT NULL,
    PROV_NM      VARCHAR(100) NOT NULL,
    PROV_TYP     VARCHAR(20)  NOT NULL,
    DEPT_CD      VARCHAR(10)  NOT NULL,
    LIC_NO       VARCHAR(30),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    REG_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TB_PROVIDER PRIMARY KEY (PROV_ID),
    CONSTRAINT FK_PROV_DEPT FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT_MST (DEPT_CD)
);

CREATE TABLE TB_DGN_CD_MST (
    DGN_CD       VARCHAR(20)  NOT NULL,
    DGN_NM       VARCHAR(200) NOT NULL,
    DGN_NM_EN    VARCHAR(200),
    ICD_VER      VARCHAR(10)  NOT NULL DEFAULT 'KCD8',
    CAT_CD       VARCHAR(20),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_DGN_CD_MST PRIMARY KEY (DGN_CD)
);

CREATE TABLE TB_LAB_MST (
    EXM_CD       VARCHAR(20)  NOT NULL,
    EXM_NM       VARCHAR(150) NOT NULL,
    EXM_NM_EN    VARCHAR(150),
    EXM_CAT      VARCHAR(30)  NOT NULL,
    SPEC_TYP     VARCHAR(30),
    UNIT_CD      VARCHAR(20),
    METHOD_CD    VARCHAR(30),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_LAB_MST PRIMARY KEY (EXM_CD)
);

CREATE TABLE TB_LAB_REF (
    REF_ID       BIGSERIAL    NOT NULL,
    EXM_CD       VARCHAR(20)  NOT NULL,
    SEX_CD       CHAR(1)      NOT NULL DEFAULT 'A',
    AGE_FROM     INTEGER      NOT NULL DEFAULT 0,
    AGE_TO       INTEGER      NOT NULL DEFAULT 150,
    LOW_VAL      NUMERIC(12,4),
    HIGH_VAL     NUMERIC(12,4),
    REF_TXT      VARCHAR(100),
    UNIT_CD      VARCHAR(20),
    CONSTRAINT PK_TB_LAB_REF PRIMARY KEY (REF_ID),
    CONSTRAINT FK_LAB_REF_MST FOREIGN KEY (EXM_CD) REFERENCES TB_LAB_MST (EXM_CD)
);

CREATE TABLE TB_DRUG_MST (
    DRUG_CD      VARCHAR(20)  NOT NULL,
    DRUG_NM      VARCHAR(200) NOT NULL,
    GEN_NM       VARCHAR(200),
    ATC_CD       VARCHAR(20),
    FORM_CD      VARCHAR(20),
    STR_VAL      VARCHAR(50),
    UNIT_CD      VARCHAR(20),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_DRUG_MST PRIMARY KEY (DRUG_CD)
);

CREATE TABLE TB_IMG_MST (
    IMG_CD       VARCHAR(20)  NOT NULL,
    IMG_NM       VARCHAR(150) NOT NULL,
    MODALITY     VARCHAR(20)  NOT NULL,
    BODY_PART    VARCHAR(50),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_IMG_MST PRIMARY KEY (IMG_CD)
);

CREATE TABLE TB_PROC_MST (
    PROC_CD      VARCHAR(20)  NOT NULL,
    PROC_NM      VARCHAR(200) NOT NULL,
    PROC_CAT     VARCHAR(30),
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_PROC_MST PRIMARY KEY (PROC_CD)
);

CREATE TABLE TB_DOC_TYPE (
    DOC_TYP_CD   VARCHAR(20)  NOT NULL,
    DOC_TYP_NM   VARCHAR(100) NOT NULL,
    DOC_CAT      VARCHAR(30)  NOT NULL,
    USE_YN       CHAR(1)      NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_TB_DOC_TYPE PRIMARY KEY (DOC_TYP_CD)
);

-- ------------------------------------------------------------
-- Patient / Encounter
-- ------------------------------------------------------------

CREATE TABLE TB_PT_MST (
    PT_NO        VARCHAR(20)  NOT NULL,
    PT_NM        VARCHAR(100) NOT NULL,
    BRTH_DT      DATE         NOT NULL,
    SEX_CD       CHAR(1)      NOT NULL,
    RR_NO_HASH   VARCHAR(64),
    TEL_NO       VARCHAR(20),
    ADDR_TXT     VARCHAR(300),
    BLD_TYP      VARCHAR(5),
    REG_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPD_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TB_PT_MST PRIMARY KEY (PT_NO),
    CONSTRAINT CK_PT_SEX CHECK (SEX_CD IN ('M', 'F', 'U'))
);

CREATE TABLE TB_ENC_HIST (
    ENC_ID       VARCHAR(30)  NOT NULL,
    PT_NO        VARCHAR(20)  NOT NULL,
    ENC_TYP      VARCHAR(10)  NOT NULL,
    ENC_STS      VARCHAR(10)  NOT NULL,
    DEPT_CD      VARCHAR(10)  NOT NULL,
    PROV_ID      VARCHAR(20)  NOT NULL,
    ADM_DT       TIMESTAMP    NOT NULL,
    DSCH_DT      TIMESTAMP,
    CHIEF_COMP   VARCHAR(500),
    REG_DT       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_TB_ENC_HIST PRIMARY KEY (ENC_ID),
    CONSTRAINT FK_ENC_PT FOREIGN KEY (PT_NO) REFERENCES TB_PT_MST (PT_NO),
    CONSTRAINT FK_ENC_DEPT FOREIGN KEY (DEPT_CD) REFERENCES TB_DEPT_MST (DEPT_CD),
    CONSTRAINT FK_ENC_PROV FOREIGN KEY (PROV_ID) REFERENCES TB_PROVIDER (PROV_ID),
    CONSTRAINT CK_ENC_TYP CHECK (ENC_TYP IN ('O', 'I', 'E')),
    CONSTRAINT CK_ENC_STS CHECK (ENC_STS IN ('A', 'D', 'C'))
);

CREATE TABLE TB_ADM_HIST (
    ADM_ID       VARCHAR(30)  NOT NULL,
    ENC_ID       VARCHAR(30)  NOT NULL,
    PT_NO        VARCHAR(20)  NOT NULL,
    WARD_CD      VARCHAR(10)  NOT NULL,
    BED_NO       VARCHAR(10),
    ADM_DT       TIMESTAMP    NOT NULL,
    DSCH_DT      TIMESTAMP,
    DSCH_TYP     VARCHAR(20),
    ADM_PATH     VARCHAR(20),
    CONSTRAINT PK_TB_ADM_HIST PRIMARY KEY (ADM_ID),
    CONSTRAINT FK_ADM_ENC FOREIGN KEY (ENC_ID) REFERENCES TB_ENC_HIST (ENC_ID),
    CONSTRAINT FK_ADM_PT FOREIGN KEY (PT_NO) REFERENCES TB_PT_MST (PT_NO),
    CONSTRAINT FK_ADM_WARD FOREIGN KEY (WARD_CD) REFERENCES TB_WARD_MST (WARD_CD),
    CONSTRAINT UQ_ADM_ENC UNIQUE (ENC_ID)
);

