    CONSTRAINT FK_DGN_PT FOREIGN KEY (PT_NO) REFERENCES TB_PT_MST (PT_NO),
    CONSTRAINT FK_DGN_CD FOREIGN KEY (DGN_CD) REFERENCES TB_DGN_CD_MST (DGN_CD),
    CONSTRAINT FK_DGN_PROV FOREIGN KEY (PROV_ID) REFERENCES TB_PROVIDER (PROV_ID)
